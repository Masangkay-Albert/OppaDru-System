import autoTable from 'jspdf-autotable';
import jsPDF from 'jspdf';
import { formatCurrency } from './formatters';

const formatPdfCurrency = (amount: number) => formatCurrency(amount).replace('₱', 'PHP ');

export interface FranchiseReportPdfData {
  branchName: string;
  period: string;
  generatedBy: { name: string; email: string };
  metrics: {
    totalSales: number;
    totalOrders: number;
    completedOrders: number;
    cancelledOrders: number;
    averageOrderValue: number;
  };
  products: Array<{ name: string; quantity: number; sales: number }>;
  payments: Array<{ method: string; orders: number; amount: number }>;
}

export const generateFranchiseReportPdf = (data: FranchiseReportPdfData): void => {
  const document = new jsPDF();
  const margin = 16;
  const width = document.internal.pageSize.getWidth();

  document.setFillColor(35, 122, 70);
  document.rect(0, 0, width, 5, 'F');
  document.setTextColor(27, 67, 50);
  document.setFont('helvetica', 'bold');
  document.setFontSize(18);
  document.text('Branch Sales Report', margin, 19);
  document.setFont('helvetica', 'normal');
  document.setFontSize(10);
  document.setTextColor(95, 110, 100);
  document.text(data.branchName, margin, 26);
  document.text(`Period: ${data.period}`, margin, 32);
  document.text(`Generated by: ${data.generatedBy.name} (${data.generatedBy.email})`, margin, 38);

  autoTable(document, {
    startY: 46,
    head: [['Net sales', 'Orders', 'Completed', 'Cancelled', 'Average order value']],
    body: [[
      formatPdfCurrency(data.metrics.totalSales),
      String(data.metrics.totalOrders),
      String(data.metrics.completedOrders),
      String(data.metrics.cancelledOrders),
      formatPdfCurrency(data.metrics.averageOrderValue),
    ]],
    theme: 'grid',
    headStyles: { fillColor: [35, 122, 70] },
    styles: { fontSize: 8, cellPadding: 3 },
  });

  autoTable(document, {
    startY: (document as jsPDF & { lastAutoTable?: { finalY: number } }).lastAutoTable?.finalY
      ? (document as jsPDF & { lastAutoTable: { finalY: number } }).lastAutoTable.finalY + 9
      : 65,
    head: [['Top products', 'Quantity sold', 'Sales']],
    body: data.products.length
      ? data.products.map((product) => [product.name, String(product.quantity), formatPdfCurrency(product.sales)])
      : [['No product sales', '', '']],
    theme: 'grid',
    headStyles: { fillColor: [35, 122, 70] },
    styles: { fontSize: 9, cellPadding: 3 },
  });

  const lastTableY = (document as jsPDF & { lastAutoTable?: { finalY: number } }).lastAutoTable?.finalY ?? 100;
  autoTable(document, {
    startY: lastTableY + 9,
    head: [['Payment method', 'Orders', 'Amount']],
    body: data.payments.length
      ? data.payments.map((payment) => [payment.method, String(payment.orders), formatPdfCurrency(payment.amount)])
      : [['No payment data', '', '']],
    theme: 'grid',
    headStyles: { fillColor: [35, 122, 70] },
    styles: { fontSize: 9, cellPadding: 3 },
  });

  document.save('branch-sales-report.pdf');
};
